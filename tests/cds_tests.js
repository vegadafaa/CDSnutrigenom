/**
 * NutriGen-CDS: Comprehensive Unit & Clinical Logic Test Suite
 * Validates parsers, clinical inference rules, safety contraindications, and FHIR export.
 */

const CDSTestSuite = {
  results: [],

  assert: function(condition, testName, details = "") {
    const passed = Boolean(condition);
    this.results.push({ name: testName, passed, details });
    if (!passed) {
      console.error(`FAIL: ${testName}`, details);
    } else {
      console.log(`PASS: ${testName}`);
    }
  },

  runAll: function() {
    this.results = [];
    console.log("=== Starting NutriGen-CDS Test Suite ===");

    this.testVcfParser();
    this.test23andMeParser();
    this.testRuleEngineScoring();
    this.testEpistasisRules();
    this.testSafetyAndContraindications();
    this.testBiomarkerConcordance();
    this.testFhirExporterCompliance();

    const passedCount = this.results.filter(r => r.passed).length;
    const failedCount = this.results.length - passedCount;
    console.log(`=== Tests Complete: ${passedCount}/${this.results.length} Passed (${failedCount} Failed) ===`);

    return {
      total: this.results.length,
      passed: passedCount,
      failed: failedCount,
      results: this.results
    };
  },

  testVcfParser: function() {
    const sampleVcf = `##fileformat=VCFv4.2
#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tSAMPLE1
1\t11856378\trs1801133\tG\tA\t100\tPASS\t.\tGT\t1/1
19\t45411941\trs429358\tT\tC\t100\tPASS\t.\tGT:DP\t0/1:30
6\t26093141\trs1800562\tG\tA\t100\tPASS\t.\tGT\t1/1
`;

    const parsed = GenomicParsers.parseVCF(sampleVcf, NUTRIGENOMICS_KB);
    this.assert(parsed["rs1801133"] !== undefined, "VCF Parser parses rs1801133 (MTHFR)");
    this.assert(parsed["rs1801133"].genotype === "TT" || parsed["rs1801133"].genotype === "AA", "VCF Parser correctly calls homozygous alt for rs1801133");
    this.assert(parsed["rs429358"] !== undefined, "VCF Parser parses rs429358 (APOE)");
    this.assert(parsed["rs429358"].genotype === "CT", "VCF Parser normalizes heterozygous call to CT");
    this.assert(parsed["rs1800562"] !== undefined, "VCF Parser parses rs1800562 (HFE)");
  },

  test23andMeParser: function() {
    const raw23 = `# This data file generated by 23andMe
# rsid\tchromosome\tposition\tgenotype
rs1801133\t1\t11856378\tTT
rs4680\t22\t19951271\tAA
rs762551\t15\t75042617\tCC
rs4988235\t2\t136608646\tCC
`;
    const parsed = GenomicParsers.parse23andMe(raw23, NUTRIGENOMICS_KB);
    this.assert(parsed["rs1801133"] && parsed["rs1801133"].genotype === "TT", "23andMe Parser handles MTHFR TT");
    this.assert(parsed["rs4680"] && parsed["rs4680"].genotype === "AA", "23andMe Parser handles COMT AA (Met/Met)");
    this.assert(parsed["rs762551"] && parsed["rs762551"].genotype === "CC", "23andMe Parser handles CYP1A2 CC (slow caffeine)");
    this.assert(parsed["rs4988235"] && parsed["rs4988235"].genotype === "CC", "23andMe Parser handles LCT CC (lactose intolerant)");
  },

  testRuleEngineScoring: function() {
    const patient = SAMPLE_PATIENTS[0]; // Arthur Pendelton
    const evalResult = CDSRuleEngine.evaluatePatient(patient, NUTRIGENOMICS_KB);

    this.assert(evalResult.domainAssessments !== undefined, "Rule Engine generates domain assessments");
    this.assert(evalResult.domainAssessments.Methylation.percentageScore > 0, "Methylation domain has non-zero risk score for MTHFR TT");
    this.assert(evalResult.domainAssessments.Cardiometabolic.percentageScore > 0, "Cardiometabolic domain has non-zero risk score for APOE4 / FTO");
    this.assert(evalResult.macronutrientRx.dailyCalories > 1200, "Macronutrient Rx calculates realistic daily caloric target");
    this.assert(evalResult.supplementFormulary.length >= 3, "Supplement formulary contains personalized recommendations");
  },

  testEpistasisRules: function() {
    // Test Case: MTHFR TT + COMT AA
    const testPatient = {
      id: "TEST-EPI",
      name: "Epistasis Test",
      genotypes: {
        "rs1801133": { rsid: "rs1801133", genotype: "TT", gene: "MTHFR" },
        "rs4680": { rsid: "rs4680", genotype: "AA", gene: "COMT" }
      }
    };

    const alerts = CDSRuleEngine.evaluateEpistasis(testPatient.genotypes, testPatient);
    const mthfrComtAlert = alerts.find(a => a.id === "EPI_MTHFR_COMT");
    this.assert(mthfrComtAlert !== undefined, "Epistasis engine flags MTHFR 677TT + Slow COMT AA interaction");
  },

  testSafetyAndContraindications: function() {
    // Test Case: HFE Carrier taking iron supplement
    const ironPatient = {
      id: "TEST-IRON",
      name: "Iron Test",
      supplements: ["Ferrous Sulfate 65mg daily", "Vitamin C"],
      genotypes: {
        "rs1800562": { rsid: "rs1800562", genotype: "AA", gene: "HFE" }
      }
    };

    const safetyAlerts = CDSRuleEngine.evaluateSafety(ironPatient, ironPatient.genotypes);
    const hfeAlert = safetyAlerts.find(a => a.id === "CONTRA_HFE_IRON");
    this.assert(hfeAlert !== undefined, "Safety engine triggers critical contraindication for HFE AA + Iron supplement");
    this.assert(hfeAlert && hfeAlert.severity === "critical", "HFE Iron contraindication is marked as critical severity");

    // Test Case: Warfarin + Vitamin K
    const warfarinPatient = {
      id: "TEST-WARFARIN",
      name: "Warfarin Test",
      medications: ["Warfarin 5mg"],
      supplements: ["Vitamin K2 MK-7 200mcg"],
      genotypes: {}
    };

    const warfAlerts = CDSRuleEngine.evaluateSafety(warfarinPatient, warfarinPatient.genotypes);
    const warfKAlert = warfAlerts.find(a => a.id === "ALERT_WARFARIN_VIT_K");
    this.assert(warfKAlert !== undefined, "Safety engine triggers critical warning for Warfarin + Vitamin K co-administration");
  },

  testBiomarkerConcordance: function() {
    const patient = {
      id: "TEST-CONC",
      name: "Concordance Test",
      biomarkers: {
        homocysteine: { value: 18.2, unit: "µmol/L", reference: "< 10.0", status: "elevated" },
        ferritin: { value: 550, unit: "ng/mL", reference: "30 - 300", status: "severely elevated" }
      },
      genotypes: {
        "rs1801133": { rsid: "rs1801133", genotype: "TT", variantName: "C677T" },
        "rs1800562": { rsid: "rs1800562", genotype: "AA", variantName: "C282Y" }
      }
    };

    const alerts = BiomarkerConcordance.evaluate(patient, patient.genotypes);
    const hcyAlert = alerts.find(a => a.id === "CONC_MTHFR_HCY_SEVERE");
    const ferrAlert = alerts.find(a => a.id === "CONC_HFE_FERRITIN_CRITICAL");

    this.assert(hcyAlert !== undefined, "Concordance engine flags severe hyperhomocysteinemia with MTHFR TT");
    this.assert(ferrAlert !== undefined, "Concordance engine flags emergency ferritin elevation with HFE AA");
  },

  testFhirExporterCompliance: function() {
    const patient = SAMPLE_PATIENTS[0];
    const evaluation = CDSRuleEngine.evaluatePatient(patient, NUTRIGENOMICS_KB);
    const bundle = FHIRExporter.exportToFHIRBundle(patient, evaluation);

    this.assert(bundle.resourceType === "Bundle", "FHIR Export generates resourceType = Bundle");
    this.assert(bundle.type === "collection", "FHIR Bundle is a collection");

    const patientEntry = bundle.entry.find(e => e.resource.resourceType === "Patient");
    this.assert(patientEntry !== undefined, "FHIR Bundle contains Patient resource");

    const reportEntry = bundle.entry.find(e => e.resource.resourceType === "DiagnosticReport");
    this.assert(reportEntry !== undefined, "FHIR Bundle contains DiagnosticReport (GenomicReport) resource");
    this.assert(reportEntry.resource.category[0].coding[0].code === "GE", "DiagnosticReport category is coded as Genetics (GE)");

    const nutritionOrderEntry = bundle.entry.find(e => e.resource.resourceType === "NutritionOrder");
    this.assert(nutritionOrderEntry !== undefined, "FHIR Bundle contains NutritionOrder resource");
    this.assert(nutritionOrderEntry.resource.oralDiet !== undefined, "NutritionOrder contains oralDiet element with macronutrients");
    this.assert(nutritionOrderEntry.resource.supplement.length > 0, "NutritionOrder contains precision supplement orders");

    const obsEntries = bundle.entry.filter(e => e.resource.resourceType === "Observation");
    this.assert(obsEntries.length >= 5, "FHIR Bundle contains multiple genomic and biomarker Observation resources");
  }
};

// Export
if (typeof module !== 'undefined' && module.exports) {
  module.exports = { CDSTestSuite };
} else if (typeof window !== 'undefined') {
  window.CDSTestSuite = CDSTestSuite;
}
